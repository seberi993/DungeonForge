using System.Reflection;
using System.Text;
using DungeonForge.Api.Errors;

namespace DungeonForge.Tests.Errors;

internal sealed record CoveredBy(string Code, string File, string Method);

// Renders docs/errors.md. Everything in it is derived: codes and statuses from ErrorSpec, tests from [CoversError],
// operations from the operation constants.
internal static class ErrorsDoc
{
    public static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "DungeonForge.sln")))
        {
            dir = dir.Parent;
        }

        return dir?.FullName ?? throw new InvalidOperationException("DungeonForge.sln not found above the test output.");
    }

    public static string RenderCurrent(Assembly api, Assembly tests) => Render(
        ErrorCatalog.Specs(api),
        [.. tests.GetTypes()
            .SelectMany(t => t.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static))
            .SelectMany(m => m.GetCustomAttributes<CoversErrorAttribute>().Select(a => new CoveredBy(a.Code, a.File, m.Name)))],
        ErrorCatalog.Operations(api));

    public static string Render(IReadOnlyList<ErrorSpec> specs, IReadOnlyList<CoveredBy> covers, IReadOnlyList<OperationInfo> operations)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Errors");
        sb.AppendLine();
        sb.AppendLine("Generated by `ErrorsDocTests` from the error catalog. Do not edit by hand: change the spec, the `[CoversError]` test or the");
        sb.AppendLine("operation constant, then run `UPDATE_ERRORS_DOC=1 dotnet test --filter ErrorsDocTests`.");
        sb.AppendLine();
        sb.AppendLine("Every non-2xx response except the waiting 409 is `application/problem+json` with `code`, `operation`, `parameters` and");
        sb.AppendLine("`traceId`. A 400 also carries `errors` (field to messages). A handler with no failure path may return its value directly.");
        sb.AppendLine("The waiting 409 is a success variant: `{ partyId, locked, required, lockStatus, status: \"waiting\" }`, no code.");
        sb.AppendLine();
        sb.AppendLine("To trace a failure: code -> `ErrorCodes` constant -> its `ErrorSpec` (the \"Defined in\" file) -> the handler that returns it ->");
        sb.AppendLine("the covering test. Search the code string to land on all of them.");
        sb.AppendLine();
        sb.AppendLine("## Codes");
        sb.AppendLine();
        sb.AppendLine("| Code | Kind | Status | Description | Defined in | Covered by |");
        sb.AppendLine("|---|---|---|---|---|---|");
        foreach (var spec in specs.OrderBy(s => s.Code, StringComparer.Ordinal))
        {
            var tests = covers.Where(c => c.Code == spec.Code)
                .Select(c => $"`{Repo(c.File)}#{c.Method}`")
                .OrderBy(t => t, StringComparer.Ordinal)
                .ToList();
            sb.AppendLine(
                $"| `{spec.Code}` | {spec.Kind} | {spec.StatusCode} | {spec.Description} | `{Repo(spec.DeclaredIn)}` | " +
                $"{(tests.Count == 0 ? "none" : string.Join(", ", tests))} |");
        }

        sb.AppendLine();
        sb.AppendLine("## Operations");
        sb.AppendLine();
        sb.AppendLine("The `operation` of an error or coded log event, and the folder of the slice that owns it.");
        sb.AppendLine();
        sb.AppendLine("| Operation | Folder |");
        sb.AppendLine("|---|---|");
        foreach (var op in operations.OrderBy(o => o.Operation, StringComparer.Ordinal))
        {
            sb.AppendLine($"| `{op.Operation}` | `{op.Folder}` |");
        }

        sb.AppendLine();
        sb.AppendLine("## Log events");
        sb.AppendLine();
        sb.AppendLine("Failures outside a request's reply are coded log events, not errors: see `src/DungeonForge.Api/Errors/LogEvents.cs`.");
        sb.AppendLine("Each has a stable `EventId` and `EventName` and is logged inside an `Operation`/`PartyId`/`Turn` scope.");
        return sb.ToString();
    }

    // Repo-relative path from a compile-time absolute one, whichever machine built it.
    private static string Repo(string file)
    {
        var path = file.Replace('\\', '/');
        foreach (var marker in new[] { "/src/DungeonForge.", "/tests/DungeonForge." })
        {
            var at = path.IndexOf(marker, StringComparison.Ordinal);
            if (at >= 0)
            {
                return path[(at + 1)..];
            }
        }

        return path;
    }
}
